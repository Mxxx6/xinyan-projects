    y0 = pdf.get_y(); pdf.set_fill_color(245,245,250); pdf.set_font("C","",sz)
    x=M; xs=[x]
    for w in col_w[:-1]: x+=w; xs.append(x)
    for j,h in enumerate(headers): pdf.set_xy(xs[j],y0); pdf.cell(col_w[j],6,h,border=1,fill=True,align="C")
    pdf.set_y(y0+6)
    for row in rows:
        y=pdf.get_y(); pdf.set_font("C","",sz-1)
        for j,v in enumerate(row): pdf.set_xy(xs[j],y); pdf.cell(col_w[j],5,str(v)[:35],border=1,align="C")
        pdf.set_y(y+5)

